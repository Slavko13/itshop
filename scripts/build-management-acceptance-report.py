def page_background(canvas, doc):
    page = canvas.getPageNumber()
    canvas.saveState()
    if page == 1:
        canvas.setFillColor(PURPLE_DARK)
        canvas.rect(0, 0, PAGE_W, PAGE_H, stroke=0, fill=1)
        canvas.setFillColor(PURPLE)
        canvas.circle(PAGE_W - 8 * mm, 20 * mm, 65 * mm, stroke=0, fill=1)
    else:
        canvas.setFillColor(BG)
        canvas.rect(0, 0, PAGE_W, PAGE_H, stroke=0, fill=1)
        canvas.setStrokeColor(LINE)
        canvas.line(18 * mm, PAGE_H - 15 * mm, PAGE_W - 18 * mm, PAGE_H - 15 * mm)
        canvas.setFont("Arial-Bold", 8)
        canvas.setFillColor(PURPLE)
        canvas.drawString(18 * mm, PAGE_H - 11 * mm, "ITSOFT - ТЕХНИЧЕСКАЯ ПРИЁМКА")
        canvas.setFont("Arial", 8)
        canvas.setFillColor(MUTED)
        canvas.drawRightString(PAGE_W - 18 * mm, 10 * mm, str(page))
    canvas.restoreState()


