def section(kicker, title, text=None):
    parts = [P(kicker.upper(), "EyebrowRU"), P(title, "H2RU")]
    if text:
        parts.append(P(text))
    return parts


def simple_table(rows, widths, header=True):
    data = []
    for i, row in enumerate(rows):
        style = "CellBoldRU" if i == 0 and header else "CellRU"
        data.append([P(str(cell), style) for cell in row])
    table = Table(data, colWidths=widths, repeatRows=1 if header else 0)
    commands = [
        ("GRID", (0, 0), (-1, -1), 0.45, LINE),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 2.7 * mm),
        ("RIGHTPADDING", (0, 0), (-1, -1), 2.7 * mm),
        ("TOPPADDING", (0, 0), (-1, -1), 2.4 * mm),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 2.4 * mm),
        ("ROWBACKGROUNDS", (0, 1 if header else 0), (-1, -1), [WHITE, colors.HexColor("#FBFBFD")]),
    ]
    if header:
        commands += [
            ("BACKGROUND", (0, 0), (-1, 0), PURPLE_DARK),
            ("TEXTCOLOR", (0, 0), (-1, 0), WHITE),
        ]
    table.setStyle(TableStyle(commands))
    return table


